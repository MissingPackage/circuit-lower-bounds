# C1: topology generator coverage vs naive enumeration + first-use canonicalisation
def naive(k, s):
    n = k + s
    choices = [list(itertools.combinations(range(i), 2)) for i in range(k, n)]
    for P in itertools.product(*choices):
        deg = [0]*n
        for a, b in P: deg[a] += 1; deg[b] += 1
        if all(deg[v] >= 1 for v in range(n-1)):
            yield P
def canon(k, P):
    lab = {}; nxt = 0
    for a, b in P:
        new = [v for v in (a, b) if v < k and v not in lab]
        for v in new: lab[v] = nxt; nxt += 1
    f = lambda v: lab[v] if v < k else v
    return tuple(tuple(sorted((f(a), f(b)))) for a, b in P)
for k, s in [(4,4),(5,4),(5,5)]:
    t0=time.time(); N = set(canon(k, P) for P in naive(k, s)); T = set(topologies(k, s))
    print(f'C1 ({k},{s}) naive-canonical={len(N)} generator={len(T)} equal={N==T} {time.time()-t0:.0f}s', flush=True)

